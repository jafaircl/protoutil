/**
 * Library provides a collection of environment and program options used to configure a CEL
 * environment for a particular use case or with a related set of functionality.
 *
 * The program options provided by a library are expected to be static and not vary between calls
 * to {@link Env.program}. Configure dynamic options directly within the `Env.program` call.
 */
export interface Library {
  /**
   * compileOptions contains options for configuring the parse and check environment.
   */
  readonly compileOptions: EnvOptions;

  /**
   * programOptions contains options included in every program generated by the environment.
   *
   * Library costTracking options configure the tracker. Only a costTracking option passed
   * directly to Env.program enables runtime cost tracking.
   */
  readonly programOptions: ProgramOptions;

  /**
   * requiredLibraries lists singleton libraries which must already be configured before this
   * library is applied.
   */
  readonly requiredLibraries?: readonly string[];
}

/**
 * SingletonLibrary refines Library to ensure that libraries in this format are configured only
 * once within the environment.
 */
export interface SingletonLibrary extends Library {
  /**
   * libraryName is a namespaced name used to check whether the library was already
   * configured in the environment.
   */
  readonly libraryName: string;
}

/**
 * LibraryAliaser provides a simple named alias for the library for use during environment
 * serialization.
 */
export interface LibraryAliaser {
  /**
   * libraryAlias is the simple name used to serialize the library.
   */
  readonly libraryAlias: string;
}

/**
 * LibrarySubsetter provides the subset description associated with the library, or `undefined`
 * when the library is not subset.
 */
export interface LibrarySubsetter {
  /**
   * librarySubset contains the subset description associated with the library.
   */
  readonly librarySubset: LibrarySubset | undefined;
}

/**
 * LibraryVersioner provides a version number for the library.
 *
 * If this interface is not implemented, the library version is flagged as latest during
 * environment serialization.
 */
export interface LibraryVersioner {
  /**
   * libraryVersion contains the configured library version.
   */
  readonly libraryVersion: number;
}

