/**
 * optionalListFirst returns the first list value as an optional.
 */
function optionalListFirst(value: Val): Val {
  return optionalListElement({ fromEnd: false, value });
}

/**
 * optionalListLast returns the last list value as an optional.
 */
function optionalListLast(value: Val): Val {
  return optionalListElement({ fromEnd: true, value });
}

/**
 * OptionalListElementOptions selects an element from a CEL list.
 */
interface OptionalListElementOptions {
  /** FromEnd selects the final element rather than the first. */
  fromEnd: boolean;
  /** Value contains the CEL list being inspected. */
  value: Val;
}

/**
 * optionalListElement returns an empty optional for empty lists and wraps the selected element.
 */
function optionalListElement(options: OptionalListElementOptions): Val {
  if (!isLister(options.value)) {
    return noSuchOverloadErr();
  }
  const size = options.value.size();
  if (!(size instanceof Int) || size.value() === 0n) {
    return size instanceof Int ? OptionalNone : noSuchOverloadErr();
  }
  const index = options.fromEnd ? size.value() - 1n : 0n;
  return optionalOf(options.value.get(new Int(index)));
}

/**
 * optionalUnwrap filters empty optional values from a list.
 */
function optionalUnwrap(value: Val): Val {
  if (!isLister(value)) {
    return noSuchOverloadErr();
  }
  const unwrapped: Val[] = [];
  const iterator = value.iterator();
  while ((iterator.hasNext() as Bool).value()) {
    const element = iterator.next();
    if (!(element instanceof Optional)) {
      return err(`value ${String(element.value())} is not optional`);
    }
    if (element.hasValue()) {
      unwrapped.push(element.getValue());
    }
  }
  return DefaultTypeAdapter.nativeToValue(unwrapped);
}

/**
 * isLister reports whether a CEL value provides the list operations used by optional helpers.
 */
function isLister(value: Val): value is Lister {
  return (
    "size" in (value as object) &&
    typeof (value as { size?: unknown }).size === "function" &&
    "get" in (value as object) &&
    typeof (value as { get?: unknown }).get === "function" &&
    "iterator" in (value as object) &&
    typeof (value as { iterator?: unknown }).iterator === "function"
  );
}

/**
 * ExpandOptionalMapOptions supplies the macro call components used by optional map expansion.
 */
interface ExpandOptionalMapOptions {
  /** Args contains the iteration variable and mapping expression. */
  args: Expr[];
  /** Flat indicates whether the mapping expression already returns an optional. */
  flat: boolean;
  /** Helper creates parser-owned expressions with consistent identifiers. */
  helper: ExprHelper;
  /** Target contains the optional receiver expression. */
  target: Expr | undefined;
}

/**
 * expandOptionalMap converts optMap and optFlatMap calls into conditional comprehensions.
 */
function expandOptionalMap(options: ExpandOptionalMapOptions): Expr | Error {
  const variable = options.args[0];
  if (variable?.kind() !== ExprKind.Ident) {
    return options.helper.error(
      variable?.id() ?? 0,
      `${options.flat ? "optFlatMap" : "optMap"}() variable name must be a simple identifier`,
    );
  }
  if (!options.target) {
    return options.helper.error(
      variable.id(),
      `${options.flat ? "optFlatMap" : "optMap"}() missing macro target`,
    );
  }
  const variableName = variable.asIdent()!;
  const mapped = options.args[1]!;
  const value = options.helper.comprehension(
    options.helper.list(),
    "#unused",
    variableName,
    options.helper.memberCall("value", options.helper.copy(options.target)),
    options.helper.literal(false),
    options.helper.ident(variableName),
    mapped,
  );

  return options.helper.call(
    operators.Conditional,
    options.helper.memberCall("hasValue", options.target),
    options.flat ? value : options.helper.call("optional.of", value),
    options.helper.call("optional.none"),
  );
}

/**
 * optionalOfNonZeroValue wraps values that do not implement zero testing or are not zero.
 */
function optionalOfNonZeroValue(value: Val): Optional {
  if (
    !("isZeroValue" in (value as object)) ||
    typeof (value as { isZeroValue?: unknown }).isZeroValue !== "function" ||
    !(value as unknown as { isZeroValue(): boolean }).isZeroValue()
  ) {
    return optionalOf(value);
  }
  return OptionalNone;
}

/**
 * decorateOptionalOr replaces optional choice calls with short-circuiting evaluation nodes.
 */
function decorateOptionalOr(value: InterpretableV2): InterpretableV2 {
  if (
    !("functionName" in value) ||
    typeof (value as { functionName?: unknown }).functionName !== "function"
  ) {
    return value;
  }
  const call = value as InterpretableCall;
  const args = call.args();
  if (args.length !== 2) {
    return value;
  }
  switch (call.functionName()) {
    case "or":
      if (call.overloadId() !== "" && call.overloadId() !== "optional_or_optional") {
        return value;
      }
      return new OptionalOrInterpretable(call.id(), args[0]!, args[1]!);
    case "orValue":
      if (call.overloadId() !== "" && call.overloadId() !== "optional_orValue_value") {
        return value;
      }
      return new OptionalOrValueInterpretable(call.id(), args[0]!, args[1]!);
    default:
      return value;
  }
}

/**
 * OptionalOrInterpretable selects the first optional when present and otherwise evaluates the
 * second optional expression.
 */
class OptionalOrInterpretable implements InterpretableV2 {
  /**
   * constructor stores the expression id and lazy optional branches.
   */
  constructor(
    private readonly idValue: number,
    private readonly lhsValue: InterpretableV2,
    private readonly rhsValue: InterpretableV2,
  ) {}

  /**
   * id returns the expression id associated with the optional choice.
   */
  public id(): number {
    return this.idValue;
  }

  /**
   * exec evaluates the left optional and evaluates the right expression only when empty.
   */
  public exec(frame: ExecutionFrame): Val {
    // Short-circuit the right branch when the left optional already has a value.
    const lhs = this.lhsValue.exec(frame);
    if (isError(lhs) || isUnknown(lhs)) {
      return lhs;
    }
    if (!(lhs instanceof Optional)) {
      return noSuchOverloadErr();
    }
    return lhs.hasValue() ? lhs : this.rhsValue.exec(frame);
  }

  /**
   * eval evaluates the optional choice against an activation.
   */
  public eval(activation: Activation): Val {
    return this.exec(asFrame({ activation }));
  }
}

/**
 * OptionalOrValueInterpretable selects the contained value when present and otherwise evaluates
 * the concrete fallback expression.
 */
class OptionalOrValueInterpretable implements InterpretableV2 {
  /**
   * constructor stores the expression id, optional branch, and lazy fallback.
   */
  constructor(
    private readonly idValue: number,
    private readonly lhsValue: InterpretableV2,
    private readonly rhsValue: InterpretableV2,
  ) {}

  /**
   * id returns the expression id associated with the optional fallback.
   */
  public id(): number {
    return this.idValue;
  }

  /**
   * exec unwraps a present optional and evaluates the fallback only when empty.
   */
  public exec(frame: ExecutionFrame): Val {
    // Short-circuit the fallback when the left optional already has a value.
    const lhs = this.lhsValue.exec(frame);
    if (isError(lhs) || isUnknown(lhs)) {
      return lhs;
    }
    if (!(lhs instanceof Optional)) {
      return noSuchOverloadErr();
    }
    return lhs.hasValue() ? lhs.getValue() : this.rhsValue.exec(frame);
  }

  /**
   * eval evaluates the optional fallback against an activation.
   */
  public eval(activation: Activation): Val {
    return this.exec(asFrame({ activation }));
  }
}
